
WHENEVER SQLERROR CONTINUE

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_count
    FROM ALL_TABLES
   WHERE OWNER = USER
     AND TABLE_NAME = 'TB_DB_MAINTENANCE_MARKER';

  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'DROP TABLE TB_DB_MAINTENANCE_MARKER PURGE';
    DBMS_OUTPUT.PUT_LINE('TB_DB_MAINTENANCE_MARKER eliminada.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Nada que limpiar: TB_DB_MAINTENANCE_MARKER no existe.');
  END IF;
END;
/

EXIT